export function dmcToAnchor(dmcCode: string): string | null {
  const m = DMC_ANCHOR_MAPPINGS.find(
    (x) => x.dmc.toUpperCase() === dmcCode.toUpperCase().trim()
  );
  return m?.anchor ?? null;
}

export function anchorToDmc(anchorCode: string): string | null {
  const m = DMC_ANCHOR_MAPPINGS.find(
    (x) => x.anchor === anchorCode.trim()
  );
  return m?.dmc ?? null;
}
